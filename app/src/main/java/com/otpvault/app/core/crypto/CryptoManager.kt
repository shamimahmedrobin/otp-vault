package com.otpvault.app.core.crypto

import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/** Result of an AES-GCM encryption: ciphertext + the unique IV used. */
data class EncryptedData(val cipherText: ByteArray, val iv: ByteArray) {
    override fun equals(other: Any?): Boolean {
        if (this === other) return true
        if (other !is EncryptedData) return false
        return cipherText.contentEquals(other.cipherText) && iv.contentEquals(other.iv)
    }
    override fun hashCode(): Int = 31 * cipherText.contentHashCode() + iv.contentHashCode()
}

/**
 * AES-256-GCM encryption backed by the Android Keystore.
 * - Key never leaves the Keystore; never hardcoded, never in SharedPreferences.
 * - A fresh random IV is generated by the cipher for every encryption.
 * - GCM tag (128 bit) authenticates ciphertext; tampering fails decryption.
 * Hardware-backed storage is used automatically when the device supports it.
 */
class CryptoManager(
    private val keyAlias: String = DEFAULT_ALIAS
) {
    // Lazy: constructing CryptoManager must not touch the Android Keystore,
    // so the explicit-key paths stay usable in plain JVM unit tests.
    private val keyStore: KeyStore by lazy {
        KeyStore.getInstance(ANDROID_KEYSTORE).apply { load(null) }
    }

    fun encrypt(plainText: String): EncryptedData {
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, getOrCreateKey())
        val iv = cipher.iv.copyOf()
        val cipherText = cipher.doFinal(plainText.toByteArray(Charsets.UTF_8))
        return EncryptedData(cipherText, iv)
    }

    /** Returns null on corrupted / tampered ciphertext instead of throwing. */
    fun decrypt(data: EncryptedData): String? = try {
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.DECRYPT_MODE, getOrCreateKey(), GCMParameterSpec(GCM_TAG_BITS, data.iv))
        String(cipher.doFinal(data.cipherText), Charsets.UTF_8)
    } catch (e: Exception) {
        null
    }

    /** Encrypt with an explicit key (used by unit-testable backup path / key rotation). */
    fun encryptWithKey(plainText: ByteArray, key: SecretKey): EncryptedData {
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, key)
        return EncryptedData(cipher.doFinal(plainText), cipher.iv.copyOf())
    }

    fun decryptWithKey(data: EncryptedData, key: SecretKey): ByteArray? = try {
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.DECRYPT_MODE, key, GCMParameterSpec(GCM_TAG_BITS, data.iv))
        cipher.doFinal(data.cipherText)
    } catch (e: Exception) {
        null
    }

    @Synchronized
    fun getOrCreateKey(): SecretKey {
        (keyStore.getEntry(keyAlias, null) as? KeyStore.SecretKeyEntry)?.let { return it.secretKey }
        val generator = KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, ANDROID_KEYSTORE)
        val spec = KeyGenParameterSpec.Builder(
            keyAlias,
            KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT
        )
            .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
            .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
            .setKeySize(256)
            .setRandomizedEncryptionRequired(true)
            .build()
        generator.init(spec)
        return generator.generateKey()
    }

    fun deleteKey() {
        if (keyStore.containsAlias(keyAlias)) keyStore.deleteEntry(keyAlias)
    }

    companion object {
        const val ANDROID_KEYSTORE = "AndroidKeyStore"
        const val TRANSFORMATION = "AES/GCM/NoPadding"
        const val GCM_TAG_BITS = 128
        const val DEFAULT_ALIAS = "otp_vault_master_key"
    }
}
